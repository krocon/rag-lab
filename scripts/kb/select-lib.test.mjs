// @ts-check
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import {
  DEFAULT_SUPPORTED_EXTENSIONS,
  contentHash,
  estimateChunks,
  inspectContent,
  isSecretPath,
  normalizeText,
  pathSkipReason,
  selectFiles,
  summarizeByExtension,
} from './select-lib.mjs';

describe('pathSkipReason', () => {
  it('accepts supported source, Markdown and text files', () => {
    for (const path of ['src/a.ts', 'README.md', 'app/App.vue', 'x.json', 'deep/a/b/c.py']) {
      assert.equal(pathSkipReason(path), undefined, path);
    }
  });

  it('names the reason for everything else', () => {
    /** @type {[string, string][]} */
    const cases = [
      ['node_modules/x/index.js', 'excluded-directory'],
      ['packages/a/dist/index.js', 'excluded-directory'],
      ['.git/config.json', 'excluded-directory'],
      ['apps/web/.angular/cache/a.json', 'excluded-directory'],
      ['.env', 'secret'],
      ['config/.env.production', 'secret'],
      ['.env.example', 'secret'],
      ['certs/server.pem', 'secret'],
      ['keys/deploy.key', 'secret'],
      ['home/id_rsa', 'secret'],
      ['home/id_ed25519.pub', 'secret'],
      ['.npmrc', 'secret'],
      ['secrets.yaml', 'secret'],
      ['pnpm-lock.yaml', 'lockfile'],
      ['sub/package-lock.json', 'lockfile'],
      ['vendor.min.js', 'minified'],
      ['styles.min.css', 'minified'],
      ['app.js.map', 'source-map'],
      ['logo.png', 'binary'],
      ['font.woff2', 'binary'],
      ['LICENSE', 'unsupported-type'],
      ['image.svg', 'unsupported-type'],
    ];
    for (const [path, reason] of cases) {
      assert.equal(pathSkipReason(path), reason, path);
    }
  });

  it('respects the supported extensions of the server', () => {
    assert.equal(pathSkipReason('a.ts', { supportedExtensions: ['.md'] }), 'unsupported-type');
  });

  it('recognises secret file names case-insensitively', () => {
    assert.ok(isSecretPath('A/.ENV'));
    assert.ok(isSecretPath('ID_RSA'));
    assert.ok(!isSecretPath('environment.ts'));
    assert.ok(!isSecretPath('docs/keys.md'));
  });
});

describe('inspectContent', () => {
  const bytes = (/** @type {string} */ text) => new TextEncoder().encode(text);
  it('returns the text of valid UTF-8 files', () => {
    assert.deepEqual(inspectContent(bytes('const a = 1;\n')), { text: 'const a = 1;\n' });
  });
  it('detects binary, invalid encoding, empty, generated and minified content', () => {
    assert.deepEqual(inspectContent(new Uint8Array([65, 0, 66])), { reason: 'binary' });
    assert.deepEqual(inspectContent(new Uint8Array([0xc3, 0x28])), { reason: 'invalid-encoding' });
    assert.deepEqual(inspectContent(bytes(' \n\t')), { reason: 'empty' });
    assert.deepEqual(inspectContent(bytes('// @generated by x\nconst a = 1;')), { reason: 'generated' });
    assert.deepEqual(inspectContent(bytes('# Title\n\nDO NOT EDIT: generated')), { reason: 'generated' });
    assert.deepEqual(inspectContent(bytes(`a\n${'x'.repeat(1001)}\n`)), { reason: 'long-lines' });
    assert.ok('text' in inspectContent(bytes(`${'x'.repeat(1000)}\n`)));
    assert.ok('text' in inspectContent(bytes(`${'x'.repeat(1500)}`), { maxLineLength: 2000 }));
  });
});

describe('normalizeText / contentHash', () => {
  it('equals the API normalisation (apps/api/src/modules/ingestion/normalize.ts)', async () => {
    // Node strips the types of the API's TypeScript module (no imports there).
    const api = await import('../../apps/api/src/modules/ingestion/normalize.ts');
    const samples = [
      '﻿line\r\nnext\rlast',
      'Café \u0000\u0007\u001F\u007F\u0085 tab\t',
      'a\n\n\n\n\nb\n \t\n\t\n  \nc',
      '\n\n\n\nstart',
      '# Title\n\n```ts\nconst x = 1;\n```\n',
      '',
    ];
    for (const sample of samples) {
      assert.equal(normalizeText(sample), api.normalizeText(sample), JSON.stringify(sample));
    }
  });

  it('hashes the normalised text like the API (CRLF and LF give the same hash)', () => {
    assert.equal(contentHash('a\r\nb'), contentHash('a\nb'));
    assert.equal(
      contentHash('hello'),
      '2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824',
    );
  });
});

describe('selectFiles', () => {
  /** @type {string} */
  let root;
  /** @type {string} */
  let outside;
  /** @param {string} path @param {string | Uint8Array} content */
  const put = async (path, content) => {
    const absolute = join(root, ...path.split('/'));
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, content);
  };

  before(async () => {
    root = await mkdtemp(join(tmpdir(), 'raglab-select-'));
    outside = await mkdtemp(join(tmpdir(), 'raglab-outside-'));
    await writeFile(join(outside, 'secret.ts'), 'export const leaked = 1;');
    await put('README.md', '# Project\n');
    await put('src/index.ts', 'export const a = 1;\n');
    await put('src/copy.ts', 'export const a = 1;\r\n'); // same normalised content
    await put('src/big.ts', `export const big = "${'x'.repeat(200)}";\n${'// pad\n'.repeat(50)}`);
    await put('src/app.min.js', 'var a=1;');
    await put('src/logo.png', new Uint8Array([137, 80, 78, 71, 0, 1]));
    await put('src/data.json', '{\n  "a": 1\n}\n');
    await put('src/fake.ts', new Uint8Array([97, 0, 98]));
    await put('node_modules/pkg/index.js', 'module.exports = 1;');
    await put('dist/out.js', 'x');
    await put('.env', 'TOKEN=abc');
    await put('config/.env.local', 'TOKEN=abc');
    await put('keys/id_rsa', 'PRIVATE');
    await put('pnpm-lock.yaml', 'lockfileVersion: 9');
    await put('logs/today.md', '# Log\n');
    await put('apps/web/.gitignore', 'generated/\n');
    await put('apps/web/generated/api.ts', 'export {};\n');
    await put('apps/web/src/main.ts', 'bootstrap();\n');
    await put('.gitignore', 'logs/\n*.local.md\n');
    await put('notes.local.md', '# Local\n');
    await put('docs/guide.md', '# Guide\n');
    await put('docs/internal/plan.md', '# Plan\n');
    await put('.raglabignore', 'docs/internal/\n');
    await symlink(join(outside, 'secret.ts'), join(root, 'src', 'link.ts'));
  });

  after(async () => {
    await rm(root, { recursive: true, force: true });
    await rm(outside, { recursive: true, force: true });
  });

  it('walks the tree, applies every .gitignore and .raglabignore and reports reasons', async () => {
    const { selected, skipped } = await selectFiles({ root, maxBytes: 300 });
    assert.deepEqual(
      selected.map((file) => file.path),
      ['README.md', 'apps/web/src/main.ts', 'docs/guide.md', 'src/copy.ts', 'src/data.json'],
    );
    const reasons = Object.fromEntries(skipped.map((file) => [file.path, file.reason]));
    assert.equal(reasons['src/index.ts'], 'duplicate');
    assert.equal(reasons['src/big.ts'], 'too-large');
    assert.equal(reasons['src/app.min.js'], 'minified');
    assert.equal(reasons['src/logo.png'], 'binary');
    assert.equal(reasons['src/fake.ts'], 'binary');
    assert.equal(reasons['src/link.ts'], 'symlink');
    assert.equal(reasons['.env'], 'secret');
    assert.equal(reasons['config/.env.local'], 'secret');
    assert.equal(reasons['keys/id_rsa'], 'secret');
    assert.equal(reasons['pnpm-lock.yaml'], 'lockfile');
    assert.equal(reasons['docs/internal/plan.md'], 'excluded-by-rule');
    // Ignored by .gitignore or always excluded: not even listed.
    for (const path of ['logs/today.md', 'notes.local.md', 'apps/web/generated/api.ts', 'node_modules/pkg/index.js', 'dist/out.js']) {
      assert.equal(reasons[path], undefined, path);
      assert.ok(!selected.some((file) => file.path === path), path);
    }
    assert.ok(selected.every((file) => file.hash.length === 64));
  });

  it('never selects secrets, not even with --include', async () => {
    const { selected } = await selectFiles({
      root,
      include: ['.env', 'config/', 'keys/', '*.ts'],
      candidates: ['.env', 'config/.env.local', 'keys/id_rsa', 'src/copy.ts'],
    });
    assert.deepEqual(selected.map((file) => file.path), ['src/copy.ts']);
  });

  it('restricts the selection with --include and removes files with --exclude', async () => {
    // gitignore semantics: `src/` matches at any depth, `/src/` only at the root.
    const anywhere = await selectFiles({ root, include: ['src/'], maxBytes: 300 });
    assert.deepEqual(
      anywhere.selected.map((file) => file.path),
      ['apps/web/src/main.ts', 'src/copy.ts', 'src/data.json'],
    );
    const included = await selectFiles({ root, include: ['/src/'], maxBytes: 300 });
    assert.deepEqual(included.selected.map((file) => file.path), ['src/copy.ts', 'src/data.json']);
    assert.ok(included.skipped.some((file) => file.path === 'README.md' && file.reason === 'not-included'));
    const excluded = await selectFiles({ root, exclude: ['*.json', 'README.md'] });
    assert.ok(!excluded.selected.some((file) => file.path.endsWith('.json')));
    assert.ok(excluded.skipped.some((file) => file.path === 'src/data.json' && file.reason === 'excluded-by-rule'));
  });

  it('uses given candidates (git ls-files) instead of walking', async () => {
    const { selected, skipped } = await selectFiles({
      root,
      candidates: ['README.md', 'logs/today.md', 'missing.md', 'dist/out.js'],
    });
    assert.deepEqual(selected.map((file) => file.path), ['README.md', 'logs/today.md']);
    assert.deepEqual(
      skipped.map((file) => [file.path, file.reason]),
      [
        ['dist/out.js', 'excluded-directory'],
        ['missing.md', 'unreadable'],
      ],
    );
  });

  it('summarises by extension and estimates chunks', async () => {
    const { selected } = await selectFiles({ root });
    const summary = summarizeByExtension(selected);
    assert.deepEqual(
      summary.map((entry) => entry.extension),
      ['.ts', '.md', '.json'],
    );
    assert.equal(
      summary.reduce((sum, entry) => sum + entry.files, 0),
      selected.length,
    );
    assert.equal(estimateChunks([{ content: 'x'.repeat(2500) }], { chunkSize: 1200, overlap: 200 }), 3);
    assert.ok(DEFAULT_SUPPORTED_EXTENSIONS.includes('.vue'));
  });
});
