// @ts-check
/**
 * File selection of `pnpm kb:import` (scripts/kb-import.mjs): which files of a source directory are
 * imported and why the others are skipped. Pure functions plus `selectFiles`, which reads the file
 * system through small, replaceable helpers. The upload itself is in import-lib.mjs.
 *
 * Order of the checks for every candidate (the first reason wins):
 * excluded directory → secret → lockfile → minified / source map → unsupported type →
 * `.raglabignore` / `--exclude` → `--include` → symlink → size → content (binary, encoding,
 * generated, long lines, empty) → duplicate content.
 */
import { createHash } from 'node:crypto';
import { lstat, open, readdir, readFile, realpath } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { IgnoreMatcher } from './gitignore.mjs';

/**
 * Extensions the API accepts (apps/api/src/modules/ingestion/file-type.ts). Used for `--dry-run`
 * without API access; a real import uses the server's list (`GET /api/system/info`).
 */
export const DEFAULT_SUPPORTED_EXTENSIONS = [
  '.md', '.markdown', '.txt', '.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs',
  '.vue', '.svelte', '.astro', '.html', '.htm', '.css', '.scss', '.json', '.yaml', '.yml',
  '.toml', '.sh', '.py', '.java', '.kt', '.go', '.rs', '.cs', '.sql',
];

/** Directory names that are never imported: dependencies, build output, caches, VCS, IDEs. */
export const EXCLUDED_DIRECTORIES = [
  'node_modules', 'bower_components', 'jspm_packages', 'vendor',
  'dist', 'build', 'out', 'coverage', '.nyc_output', 'target',
  '.git', '.hg', '.svn',
  '.angular', '.nx', '.cache', '.parcel-cache', '.turbo', '.next', '.nuxt', '.svelte-kit',
  '.astro', '.vite', '.vercel', '.netlify', '.docusaurus', '.expo', '.gradle', '.terraform',
  '__pycache__', '.venv', 'venv', '.tox', '.mypy_cache', '.pytest_cache', '.ruff_cache',
  '.idea', '.yarn', '.pnpm-store',
];

/** Lockfiles: large, generated, no knowledge in them. */
export const LOCKFILES = [
  'package-lock.json', 'npm-shrinkwrap.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb',
  'bun.lock', 'Cargo.lock', 'poetry.lock', 'Pipfile.lock', 'composer.lock', 'Gemfile.lock',
  'go.sum', 'gradle.lockfile', 'packages.lock.json', 'deno.lock', 'uv.lock',
];

/**
 * Files that may hold secrets. They are **never** uploaded – not even with `--include`.
 * Matched against the file name (case-insensitive).
 */
export const SECRET_FILE_PATTERNS = [
  /^\.env(\..*)?$/i, // .env, .env.local, .env.production, .env.example
  /\.env$/i, // production.env
  /\.(pem|key|crt|cer|der|p12|pfx|jks|keystore|ppk|asc|gpg|kdbx|ovpn)$/i,
  /^id_(rsa|dsa|ecdsa|ed25519)(\.pub)?$/i,
  /^\.?(npmrc|pypirc|netrc|htpasswd|git-credentials|dockercfg)$/i,
  /^credentials(\.[\w-]+)?$/i,
  /^(secrets?|service-account)(\.[\w-]+)*\.(json|ya?ml|toml)$/i,
  /^\.?terraform\.tfvars(\.json)?$/i,
];

/** Extensions of binary and media files (reported as `binary`, not as `unsupported-type`). */
const BINARY_EXTENSIONS = new Set([
  '.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.ico', '.bmp', '.tif', '.tiff', '.psd',
  '.mp3', '.mp4', '.m4a', '.mov', '.avi', '.webm', '.wav', '.ogg', '.flac',
  '.woff', '.woff2', '.ttf', '.otf', '.eot',
  '.zip', '.gz', '.tgz', '.bz2', '.xz', '.7z', '.rar', '.tar', '.jar', '.war',
  '.pdf', '.doc', '.docx', '.xls', '.xlsx', '.ppt', '.pptx',
  '.exe', '.dll', '.so', '.dylib', '.bin', '.class', '.o', '.a', '.wasm', '.node', '.pyc',
  '.sqlite', '.db', '.lockb',
]);

/** Default upper bound per file (1 MiB); larger source files are almost always generated. */
export const DEFAULT_MAX_BYTES = 1024 * 1024;

/** Lines longer than this mark minified or generated code (`long-lines`). */
export const DEFAULT_MAX_LINE_LENGTH = 1000;

/** Bytes read to detect binary content (NUL) before the whole file is read. */
const SNIFF_BYTES = 8000;

/** Markers of generated files in their first lines. */
const GENERATED_MARKER = /@generated|\bDO NOT EDIT\b|auto-generated|autogenerated by/i;
const GENERATED_HEAD_LINES = 5;

/**
 * Why a file is not imported.
 * @typedef {'excluded-directory' | 'secret' | 'lockfile' | 'minified' | 'source-map'
 *   | 'unsupported-type' | 'binary' | 'excluded-by-rule' | 'not-included' | 'symlink'
 *   | 'too-large' | 'invalid-encoding' | 'generated' | 'long-lines' | 'empty' | 'duplicate'
 *   | 'unreadable'} SkipReason
 */

/** Human-readable explanation of every skip reason (dry-run output, docs). */
export const SKIP_REASON_TEXT = {
  'excluded-directory': 'inside an always excluded directory (node_modules, dist, …)',
  secret: 'may contain secrets – never uploaded',
  lockfile: 'lockfile',
  minified: 'minified file',
  'source-map': 'source map',
  'unsupported-type': 'file type not supported by RAGLab',
  binary: 'binary or media file',
  'excluded-by-rule': 'excluded by .raglabignore or --exclude',
  'not-included': 'not matched by --include',
  symlink: 'symbolic link',
  'too-large': 'larger than --max-bytes',
  'invalid-encoding': 'not valid UTF-8 text',
  generated: 'marked as generated (@generated, DO NOT EDIT)',
  'long-lines': 'contains very long lines (minified or generated)',
  empty: 'empty or whitespace only',
  duplicate: 'same content as another selected file',
  unreadable: 'cannot be read',
};

/** @param {string} path */
export function extensionOf(path) {
  // Same rule as the API (`fileExtension`): from the last dot of the file name.
  const name = basename(path);
  const dot = name.lastIndexOf('.');
  return dot === -1 ? '' : name.slice(dot).toLowerCase();
}

/** @param {string} path */
function basename(path) {
  return path.slice(path.lastIndexOf('/') + 1);
}

/** @param {string} path */
export function isSecretPath(path) {
  const name = basename(path);
  return SECRET_FILE_PATTERNS.some((pattern) => pattern.test(name));
}

/**
 * Reason to skip a file based on its path alone, or `undefined` if the path is acceptable.
 * Ignore rules (`.raglabignore`, `--exclude`, `--include`) are applied separately.
 * @param {string} path relative path with `/`
 * @param {{ supportedExtensions?: readonly string[] }} [options]
 * @returns {SkipReason | undefined}
 */
export function pathSkipReason(path, options = {}) {
  const { supportedExtensions = DEFAULT_SUPPORTED_EXTENSIONS } = options;
  const segments = path.split('/');
  if (segments.slice(0, -1).some((segment) => EXCLUDED_DIRECTORIES.includes(segment))) {
    return 'excluded-directory';
  }
  const name = segments.at(-1) ?? '';
  if (isSecretPath(path)) return 'secret';
  if (LOCKFILES.includes(name)) return 'lockfile';
  if (/\.min\.[^.]+$/i.test(name) || /[-.]bundle\.js$/i.test(name)) return 'minified';
  if (/\.map$/i.test(name)) return 'source-map';
  const extension = extensionOf(path);
  if (!supportedExtensions.includes(extension)) {
    return BINARY_EXTENSIONS.has(extension) ? 'binary' : 'unsupported-type';
  }
  return undefined;
}

// ── Normalisation and hash (must equal the API: apps/api/src/modules/ingestion/normalize.ts) ──

// eslint-disable-next-line no-control-regex -- matching control characters is the point here
const CONTROL_CHARACTERS = /[\u0000-\u0008\u000B-\u001F\u007F-\u009F]/g;
const EXCESS_BLANK_LINES = /(^|\n)(?:[ \t]*\n){3,}/g;

/**
 * Same normalisation as the API (BOM, line endings, NFC, control characters, blank lines), so
 * that {@link contentHash} equals the server's `contentSha256` and unchanged files are recognised.
 * A test compares it with the API implementation.
 * @param {string} raw
 */
export function normalizeText(raw) {
  const withoutBom = raw.startsWith('﻿') ? raw.slice(1) : raw;
  return withoutBom
    .replace(/\r\n?/g, '\n')
    .normalize('NFC')
    .replace(CONTROL_CHARACTERS, '')
    .replace(EXCESS_BLANK_LINES, (_match, lead) => `${lead}\n\n`);
}

/** SHA-256 (hex) of the normalised text – the API's `contentSha256`. @param {string} text */
export function contentHash(text) {
  return createHash('sha256').update(normalizeText(text), 'utf8').digest('hex');
}

/**
 * Checks the bytes of a file. Returns the decoded text or the reason to skip it.
 * @param {Uint8Array} bytes
 * @param {{ maxLineLength?: number }} [options]
 * @returns {{ text: string } | { reason: SkipReason }}
 */
export function inspectContent(bytes, options = {}) {
  const { maxLineLength = DEFAULT_MAX_LINE_LENGTH } = options;
  if (bytes.includes(0)) return { reason: 'binary' };
  let text;
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch {
    return { reason: 'invalid-encoding' };
  }
  if (text.trim() === '') return { reason: 'empty' };
  const head = text.split('\n', GENERATED_HEAD_LINES).join('\n');
  if (GENERATED_MARKER.test(head)) return { reason: 'generated' };
  let lineStart = 0;
  for (let index = 0; index <= text.length; index++) {
    if (index === text.length || text.charCodeAt(index) === 10) {
      if (index - lineStart > maxLineLength) return { reason: 'long-lines' };
      lineStart = index + 1;
    }
  }
  return { text };
}

/**
 * @typedef {{ path: string, bytes: number, hash: string, content: string }} SelectedFile
 * @typedef {{ path: string, reason: SkipReason, duplicateOf?: string }} SkippedFile
 * @typedef {{
 *   root: string,
 *   candidates?: string[],
 *   supportedExtensions?: readonly string[],
 *   include?: string[],
 *   exclude?: string[],
 *   maxBytes?: number,
 *   maxLineLength?: number,
 * }} SelectOptions
 */

/**
 * Selects the files to import below `root`.
 *
 * - `candidates` (relative paths, e.g. from `git ls-files`) are used as given; without them the
 *   directory is walked and every `.gitignore` in the tree is applied relative to its directory.
 * - `.raglabignore` in `root` (gitignore syntax) and `exclude` patterns remove files, `include`
 *   patterns (if any) restrict the selection. None of them can bring back a skipped secret,
 *   lockfile, binary or file in an always excluded directory.
 * - Content duplicates are kept once (the first path in sorted order).
 *
 * @param {SelectOptions} options
 * @returns {Promise<{ selected: SelectedFile[], skipped: SkippedFile[] }>}
 */
export async function selectFiles(options) {
  const {
    root,
    supportedExtensions = DEFAULT_SUPPORTED_EXTENSIONS,
    include = [],
    exclude = [],
    maxBytes = DEFAULT_MAX_BYTES,
    maxLineLength = DEFAULT_MAX_LINE_LENGTH,
  } = options;
  const realRoot = await realpath(root);

  const rules = new IgnoreMatcher();
  const raglabignore = await readFile(join(realRoot, '.raglabignore'), 'utf8').catch(() => '');
  rules.add(raglabignore);
  rules.add(exclude);
  const includeRules = new IgnoreMatcher().add(include);

  /** @type {SkippedFile[]} */
  const skipped = [];
  const candidates = options.candidates ?? (await walk(realRoot, skipped));

  /** @type {{ path: string, bytes: number, hash: string, content: string }[]} */
  const accepted = [];
  for (const path of [...new Set(candidates)].sort(comparePaths)) {
    const reason = pathSkipReason(path, { supportedExtensions });
    if (reason) {
      skipped.push({ path, reason });
      continue;
    }
    if (rules.ignores(path)) {
      skipped.push({ path, reason: 'excluded-by-rule' });
      continue;
    }
    if (include.length > 0 && !includeRules.ignores(path)) {
      skipped.push({ path, reason: 'not-included' });
      continue;
    }
    const absolute = join(realRoot, ...path.split('/'));
    let stats;
    try {
      stats = await lstat(absolute);
    } catch {
      skipped.push({ path, reason: 'unreadable' });
      continue;
    }
    // Symbolic links are never followed: a link may point outside the source directory, and a
    // link inside it duplicates a file that is imported anyway.
    if (stats.isSymbolicLink()) {
      skipped.push({ path, reason: 'symlink' });
      continue;
    }
    if (!stats.isFile()) {
      skipped.push({ path, reason: 'unreadable' });
      continue;
    }
    if (stats.size > maxBytes) {
      skipped.push({ path, reason: 'too-large' });
      continue;
    }
    let bytes;
    try {
      bytes = await readFileChecked(absolute, stats.size);
    } catch {
      skipped.push({ path, reason: 'unreadable' });
      continue;
    }
    if (bytes === 'binary') {
      skipped.push({ path, reason: 'binary' });
      continue;
    }
    const inspected = inspectContent(bytes, { maxLineLength });
    if ('reason' in inspected) {
      skipped.push({ path, reason: inspected.reason });
      continue;
    }
    accepted.push({
      path,
      bytes: stats.size,
      hash: contentHash(inspected.text),
      content: inspected.text,
    });
  }

  /** @type {Map<string, string>} */
  const firstByHash = new Map();
  /** @type {SelectedFile[]} */
  const selected = [];
  for (const file of accepted) {
    const duplicateOf = firstByHash.get(file.hash);
    if (duplicateOf !== undefined) {
      skipped.push({ path: file.path, reason: 'duplicate', duplicateOf });
      continue;
    }
    firstByHash.set(file.hash, file.path);
    selected.push(file);
  }
  skipped.sort((a, b) => comparePaths(a.path, b.path));
  return { selected, skipped };
}

/**
 * Reads a file, checking its first bytes for NUL before reading the rest.
 * @param {string} absolute
 * @param {number} size
 * @returns {Promise<Uint8Array | 'binary'>}
 */
async function readFileChecked(absolute, size) {
  const handle = await open(absolute, 'r');
  try {
    const head = new Uint8Array(Math.min(size, SNIFF_BYTES));
    await handle.read(head, 0, head.length, 0);
    if (head.includes(0)) return 'binary';
    return await handle.readFile();
  } finally {
    await handle.close();
  }
}

/** Byte-wise order of paths (stable across platforms and locales). @param {string} a @param {string} b */
export function comparePaths(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * Walks `root` recursively without following symbolic links; applies every `.gitignore` relative
 * to its directory and never enters always excluded directories. Ignored files are not reported
 * (like Git, they do not exist for the import); symbolic links are returned as candidates so they
 * are reported as skipped.
 * @param {string} root
 * @param {SkippedFile[]} skipped
 * @returns {Promise<string[]>}
 */
async function walk(root, skipped) {
  const gitignore = new IgnoreMatcher();
  /** @type {string[]} */
  const files = [];
  /** @param {string} directory relative, '' = root */
  async function visit(directory) {
    const absolute = directory === '' ? root : join(root, ...directory.split('/'));
    const text = await readFile(join(absolute, '.gitignore'), 'utf8').catch(() => undefined);
    if (text !== undefined) {
      gitignore.add(text, directory);
    }
    let entries;
    try {
      entries = await readdir(absolute, { withFileTypes: true });
    } catch {
      skipped.push({ path: directory || '.', reason: 'unreadable' });
      return;
    }
    entries.sort((a, b) => comparePaths(a.name, b.name));
    for (const entry of entries) {
      const path = directory === '' ? entry.name : `${directory}/${entry.name}`;
      if (entry.isDirectory()) {
        if (EXCLUDED_DIRECTORIES.includes(entry.name) || gitignore.ignores(path, true)) {
          continue;
        }
        await visit(path);
      } else if ((entry.isFile() || entry.isSymbolicLink()) && !gitignore.ignores(path)) {
        files.push(path);
      }
    }
  }
  await visit('');
  return files;
}

/**
 * Relative path with `/` for an absolute path below `root`.
 * @param {string} root
 * @param {string} absolute
 */
export function toRelativePath(root, absolute) {
  return relative(root, absolute).split(sep).join('/');
}

/**
 * Summary per extension: number of files and bytes, sorted by count.
 * @param {{ path: string, bytes: number }[]} files
 */
export function summarizeByExtension(files) {
  /** @type {Map<string, { extension: string, files: number, bytes: number }>} */
  const summary = new Map();
  for (const file of files) {
    const extension = extensionOf(file.path) || '(none)';
    const entry = summary.get(extension) ?? { extension, files: 0, bytes: 0 };
    entry.files += 1;
    entry.bytes += file.bytes;
    summary.set(extension, entry);
  }
  return [...summary.values()].sort((a, b) => b.files - a.files || comparePaths(a.extension, b.extension));
}

/**
 * Rough number of chunks: characters / (chunk size − overlap), at least one per file. Only an
 * estimate – the code chunker keeps small declarations together and splits at line ends.
 * @param {{ content: string }[]} files
 * @param {{ chunkSize?: number, overlap?: number }} [options]
 */
export function estimateChunks(files, options = {}) {
  const { chunkSize = 1200, overlap = 200 } = options;
  const step = Math.max(1, chunkSize - overlap);
  return files.reduce((sum, file) => sum + Math.max(1, Math.ceil(file.content.length / step)), 0);
}
