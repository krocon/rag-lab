/** Generates the random id of the content markers of one tool result. */
export type BoundaryFactory = () => string;

export const randomBoundary: BoundaryFactory = () => randomBytes(6).toString('hex');

/**
 * Encloses untrusted text in markers with the tool result's random `boundary`. Should the text
 * contain the boundary anyway, it is altered, so the block cannot be closed early.
 */
export function untrustedBlock(text: string, boundary: string): string {
  const safe = text.split(boundary).join(`${boundary.slice(0, 1)}⁠${boundary.slice(1)}`);
  return [
    `<<<BEGIN UNTRUSTED CONTENT ${boundary}>>>`,
    safe,
    `<<<END UNTRUSTED CONTENT ${boundary}>>>`,
  ].join('\n');
}

export interface Truncated {
  text: string;
  truncated: boolean;
}

/**
 * Cuts `text` to at most `maxChars` UTF-16 code units without splitting a surrogate pair.
 */
export function truncate(text: string, maxChars: number): Truncated {
  if (text.length <= maxChars) {
    return { text, truncated: false };
  }
  let end = Math.max(0, maxChars);
  const last = text.charCodeAt(end - 1);
  if (end > 0 && last >= 0xd800 && last <= 0xdbff) {
    end -= 1;
  }
  return { text: text.slice(0, end), truncated: true };
}

/** Final guard: the text of one tool result never exceeds `maxChars`. */
export function capText(text: string, maxChars: number): string {
  const marker = '\n[output truncated: MCP_MAX_OUTPUT_CHARS reached]';
  if (text.length <= maxChars) {
    return text;
  }
  return truncate(text, Math.max(0, maxChars - marker.length)).text + marker;
}

/** Human-readable text of a tool error (shown to the MCP client with `isError: true`). */
export function errorText(error: RaglabApiError | ToolInputError): string {
  if (error instanceof ToolInputError) {
    return `Error ${error.code}: ${error.message}`;
  }
  const status = error.status > 0 ? ` (HTTP ${error.status})` : '';
  const lines = [`RAGLab API error ${error.code}${status}: ${error.message}`];
  const issues = validationIssues(error.details);
  if (issues.length > 0) {
    lines.push(...issues.map((issue) => `- ${issue}`));
  }
  const retryAfter = retryAfterSeconds(error.details);
  if (retryAfter !== undefined) {
    lines.push(`Retry after ${retryAfter} s.`);
  }
  return lines.join('\n');
}

function validationIssues(details: unknown): string[] {
  if (!Array.isArray(details)) {
    return [];
  }
  return details
    .filter(
      (item): item is { location: string; message: string } =>
        typeof item === 'object' &&
        item !== null &&
        typeof (item as { location?: unknown }).location === 'string' &&
        typeof (item as { message?: unknown }).message === 'string',
    )
    .slice(0, 10)
    .map((item) => `${item.location}: ${item.message}`);
}

function retryAfterSeconds(details: unknown): number | undefined {
  if (typeof details === 'object' && details !== null && 'retryAfterSeconds' in details) {
    const value = (details as { retryAfterSeconds: unknown }).retryAfterSeconds;
    return typeof value === 'number' ? value : undefined;
  }
  return undefined;
}

/** Score/distance with four decimals (raw values stay in `structuredContent`). */
export function formatNumber(value: number): string {
  return value.toFixed(4);
}

export function headingText(headingPath: readonly string[]): string {
  return headingPath.length > 0 ? headingPath.join(' > ') : '(no heading)';
}
