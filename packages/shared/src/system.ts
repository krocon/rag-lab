export type ComponentStatus = 'up' | 'down';

/** Response of `GET /api/health` (liveness – the process is running). */
export interface LivenessResponse {
  status: 'ok';
  service: 'raglab-api';
  version: string;
  uptimeSeconds: number;
  timestamp: string;
}

/** Response of `GET /api/health/ready` (readiness – dependencies are usable). */
export interface ReadinessResponse {
  status: 'ready' | 'not_ready';
  checks: {
    database: { status: ComponentStatus; latencyMs?: number; error?: string };
    pgvector: { status: ComponentStatus; version?: string; error?: string };
    /**
     * Database schema matches the configuration: the dimension of `chunks.embedding`
     * (`actual`, `null` if the column is missing) equals `EMBEDDING_DIMENSIONS` (`expected`).
     */
    schema: {
      status: ComponentStatus;
      expected: number;
      actual?: number | null;
      error?: string;
    };
  };
  timestamp: string;
}

/**
 * Response of `GET /api/system/info`: the *configured* providers.
 * Values come from configuration; nothing here proves that a provider is reachable.
 */
export interface SystemInfoResponse {
  version: string;
  nodeVersion: string;
  embedding: {
    provider: string;
    model: string;
    dimensions: number;
  };
  chat: {
    provider: string;
    model: string;
  };
  retrieval: {
    defaultTopK: number;
    /** Maximum query length in characters after trimming (`MAX_QUERY_CHARS`). */
    maxQueryChars: number;
  };
  chunking: {
    targetSize: number;
    overlap: number;
  };
  /** Upload limits of `POST /api/collections/:id/documents`. */
  upload: {
    maxFileBytes: number;
    maxFiles: number;
    allowedExtensions: string[];
  };
}

/**
 * Live state of the embedding provider in `GET /api/system/providers`. Only what was actually
 * checked is reported: `dimensions.verified` exists only after a test embedding (`?verify=true`).
 */
export interface EmbeddingProviderStatusDto {
  provider: string;
  model: string;
  /** The provider answered the availability check (Ollama: `GET /api/tags`). */
  reachable: boolean;
  /** The configured model is installed; `null` = unknown (provider not reachable). */
  modelAvailable: boolean | null;
  dimensions: {
    /** `EMBEDDING_DIMENSIONS`. */
    configured: number;
    /** Dimension of the `chunks.embedding` column; `null` if it could not be read. */
    column: number | null;
    /** Vector length returned by the test embedding; only present after `?verify=true`. */
    verified?: number;
  };
  verification: {
    status: 'skipped' | 'passed' | 'failed';
    /** Provider error code when `failed`, e.g. `MODEL_NOT_FOUND`, `DIMENSION_MISMATCH`. */
    code?: string;
    error?: string;
    durationMs?: number;
  };
  /** Problem found by the availability check (human-readable). */
  error?: string;
  /** What to do about it, e.g. `Run "ollama pull nomic-embed-text" …`. */
  hint?: string;
}

/**
 * Live state of the chat provider in `GET /api/system/providers` (reachability and model only;
 * nothing is generated by the check).
 */
export interface ChatProviderStatusDto {
  provider: string;
  model: string;
  reachable: boolean;
  /** The configured model is installed; `null` = unknown (provider not reachable). */
  modelAvailable: boolean | null;
  error?: string;
  /** What to do about it, e.g. `Run "ollama pull llama3.2" …`. */
  hint?: string;
}

/** Response of `GET /api/system/providers`. */
export interface ProvidersStatusResponse {
  embedding: EmbeddingProviderStatusDto;
  chat: ChatProviderStatusDto;
  checkedAt: string;
}
